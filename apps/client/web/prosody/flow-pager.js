// DOM-only preparation / recording / results navigation. It never starts,
// stops or evaluates audio; the owner supplies the current navigation guards.
const INTERACTIVE_TAGS = new Set(['input', 'textarea', 'select', 'button', 'a', 'label', 'summary']);
const NEXT_LABELS = ['녹음하기 →', '결과 보기 →'];

function interactiveTarget(target, boundary) {
  for (let node = target; node; node = node.parentElement || node.parentNode) {
    if (INTERACTIVE_TAGS.has(String(node.tagName || '').toLowerCase())) return true;
    const editable = node.getAttribute?.('contenteditable');
    if (node.isContentEditable || (editable !== null && editable !== undefined && String(editable).toLowerCase() !== 'false')) return true;
    if (node === boundary) break;
  }
  return false;
}

export function createFlowPager({
  pages,
  stepButtons = [],
  previousButton,
  nextButton,
  positionLabel,
  gestureTarget,
  canEnter = () => true,
  canMove = () => true,
  onChanged = () => {},
} = {}) {
  const panes = Array.from(pages || []), steps = Array.from(stepButtons || []);
  if (!panes.length) throw new TypeError('At least one flow page is required.');
  let index = 0, destroyed = false, gesture = null, pendingClick = null;
  const cleanups = [];
  const validIndex = value => Number.isInteger(value) && value >= 0 && value < panes.length;
  const allowed = value => validIndex(value) && Boolean(canEnter(value));
  const movable = () => Boolean(canMove());

  function listen(element, type, listener, options) {
    if (!element) return;
    element.addEventListener(type, listener, options);
    cleanups.push(() => element.removeEventListener(type, listener, options));
  }

  // Availability may change during analysis or guide generation. Refresh only
  // reflects that state; it must not relocate the user or invoke onChanged.
  function refresh() {
    if (destroyed) return;
    const moving = movable();
    panes.forEach((pane, at) => {
      pane.hidden = at !== index;
      pane.inert = at !== index;
      pane.setAttribute('aria-hidden', String(at !== index));
    });
    steps.forEach((button, at) => {
      if (at === index) button.setAttribute('aria-current', 'step');
      else button.removeAttribute('aria-current');
      button.disabled = !moving || !allowed(at);
      button.setAttribute('aria-disabled', String(button.disabled));
    });
    if (previousButton) previousButton.disabled = !moving || !allowed(index - 1);
    if (nextButton) {
      const last = index === panes.length - 1;
      nextButton.hidden = last;
      nextButton.disabled = last || !moving || !allowed(index + 1);
      if (!last) nextButton.textContent = NEXT_LABELS[index] || '다음 →';
    }
    if (positionLabel) positionLabel.textContent = `${index + 1} / ${panes.length}`;
  }

  function goTo(next) {
    if (destroyed || !validIndex(next)) return false;
    if (next === index) {
      refresh();
      return false;
    }
    if (!movable() || !allowed(next)) {
      refresh();
      return false;
    }
    const direction = next > index ? 'forward' : 'backward';
    index = next;
    panes[index].dataset.direction = direction;
    refresh();
    onChanged(index);
    return true;
  }

  steps.forEach((button, at) => {
    listen(button, 'click', event => {
      event.preventDefault();
      goTo(at);
    });
  });
  listen(previousButton, 'click', event => {
    event.preventDefault();
    goTo(index - 1);
  });
  listen(nextButton, 'click', event => {
    event.preventDefault();
    goTo(index + 1);
  });

  // Arrow navigation is scoped to the navigation buttons themselves. No
  // document-level key handler can steal editing keys from the script field.
  for (const button of [...steps, previousButton, nextButton].filter(Boolean)) {
    listen(button, 'keydown', event => {
      if (event.target !== button || event.altKey || event.ctrlKey || event.metaKey || event.shiftKey) return;
      const delta = event.key === 'ArrowLeft' ? -1 : event.key === 'ArrowRight' ? 1 : 0;
      if (delta && goTo(index + delta)) {
        event.preventDefault();
        steps[index]?.focus?.({ preventScroll: true });
      }
    });
  }

  listen(gestureTarget, 'pointerdown', event => {
    // A fresh tap is a new interaction, not the click generated by a previous
    // swipe. In particular, a quick subsequent control tap must work normally.
    pendingClick = null;
    // A second finger cancels an existing gesture rather than turning a pinch
    // or other multi-touch operation into an accidental page change.
    if (event.isPrimary === false || (gesture && gesture.id !== event.pointerId)) {
      gesture = null;
      return;
    }
    gesture = null;
    if (!movable() || (Number.isFinite(event.button) && event.button !== 0)
      || interactiveTarget(event.target, gestureTarget)
      || !Number.isFinite(event.clientX) || !Number.isFinite(event.clientY)) return;
    gesture = { id: event.pointerId, x: event.clientX, y: event.clientY };
  }, { passive: true });
  listen(gestureTarget, 'pointermove', event => {
    if (!gesture || gesture.id !== event.pointerId) return;
    const dx = Math.abs(event.clientX - gesture.x), dy = Math.abs(event.clientY - gesture.y);
    if (!movable() || interactiveTarget(event.target, gestureTarget) || (dy >= 12 && dy >= dx)) gesture = null;
  }, { passive: true });
  listen(gestureTarget, 'pointerup', event => {
    if (!gesture || gesture.id !== event.pointerId) return;
    const start = gesture;
    gesture = null;
    if (!movable() || interactiveTarget(event.target, gestureTarget)) return;
    const dx = event.clientX - start.x, dy = event.clientY - start.y;
    if (!Number.isFinite(dx) || !Number.isFinite(dy) || Math.abs(dx) < 50 || Math.abs(dx) <= Math.abs(dy) * 1.5) return;
    if (goTo(index + (dx < 0 ? 1 : -1))) {
      // Browsers can synthesize a click on the old, now hidden canvas after a
      // pointer swipe. Consume that one immediate click in capture phase so it
      // cannot select an old graph region or invoke a hidden pane's handler.
      pendingClick = { until: Date.now() + 400, x: event.clientX, y: event.clientY };
      if (event.cancelable !== false) event.preventDefault();
    }
  });
  listen(gestureTarget, 'pointercancel', () => { gesture = null; }, { passive: true });
  listen(gestureTarget, 'click', event => {
    if (!pendingClick) return;
    if (Date.now() > pendingClick.until) { pendingClick = null; return; }
    if (event.detail === 0) return; // Keyboard and programmatic activation.
    const previous = pendingClick;
    pendingClick = null;
    if (Number.isFinite(event.clientX) && Number.isFinite(event.clientY)
      && (Math.abs(event.clientX - previous.x) > 25 || Math.abs(event.clientY - previous.y) > 25)) return;
    event.preventDefault();
    event.stopImmediatePropagation();
    event.stopPropagation();
  }, { capture: true });

  refresh();
  return {
    goTo,
    refresh,
    get index() { return index; },
    destroy() {
      if (destroyed) return;
      destroyed = true;
      gesture = null;
      pendingClick = null;
      cleanups.splice(0).forEach(remove => remove());
    },
  };
}
