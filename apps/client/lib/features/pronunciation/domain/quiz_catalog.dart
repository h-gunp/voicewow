/// Original exercises reviewed against National Institute of Korean Language
/// rules. Sentence options are readings of individual eojeols; optional changes
/// across spaces and vowel length are outside the scoring scope.
enum TrainingCategory {
  words('단어', '발음 규칙별로 짧게 익혀요'),
  basic('기초 문장', '짧은 생활 표현을 연습해요'),
  extended('확장 문장', '상황에 맞는 문장을 익혀요'),
  business('비즈니스 문장', '업무에서 쓰는 표현을 연습해요');

  const TrainingCategory(this.label, this.subtitle);
  final String label;
  final String subtitle;
}

class QuizItem {
  const QuizItem({
    required this.id,
    required this.category,
    required this.group,
    required this.text,
    required this.pronunciation,
    required this.distractor,
    required this.explanation,
    required this.sourceUrl,
  });

  /// Compact notation for the independently curated, immutable catalog below.
  const QuizItem.entry(
    this.id,
    this.category,
    this.group,
    this.text,
    this.pronunciation,
    this.distractor,
    this.explanation,
    this.sourceUrl,
  );

  final String id;
  final TrainingCategory category;
  final String group;
  final String text;
  final String pronunciation;
  final String distractor;
  final String explanation;

  /// Official reference for the exercise's main contrast. Additional changes
  /// within the same sentence follow the references collected in [quizSources].
  final String sourceUrl;
}

