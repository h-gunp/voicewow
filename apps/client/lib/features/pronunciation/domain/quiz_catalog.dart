/// Display a short heading while keeping the full group string as its stable
/// filter value. Sentence topics have no parenthetical practice label.
String groupTitle(String group) =>
    group.replaceFirst(RegExp(r' \([^()]+\)$'), '');

String? groupPracticeLabel(String group) =>
    RegExp(r' \(([^()]+)\)$').firstMatch(group)?.group(1);

